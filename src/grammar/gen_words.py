"""Generate the word-list lexers from src/lists/ and compile them with ANTLR into src/urlfeat/parser/.

One lexer grammar per list, so every list is matched on its own (left-most, longest word at each position, exactly what the old compiled alternations did):
  WordsPhrase     suspicious_words.tsv group phrase      WordsBrand      group brand      WordsHost    group host
  WordsBrandLong  brands (Tranco top 500 labels minus the stoplist) of at least 6 characters
  WordsToken      maximal [a-z0-9] runs (whole-token matches: kit words, brand tokens)
Each grammar has one token WORD (all words as alternatives) and ANY (every other character); the visit methods keep the WORD tokens.
Words with quotes, backslashes, whitespace other than a plain space or control characters are rejected before they reach a grammar file.

    cd src/grammar && ../../.venv/bin/python gen_words.py            (needs java; the jar is in this folder)"""
import pathlib
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
LISTS = HERE.parent / "lists"
OUT = HERE.parent / "urlfeat" / "parser"


def read(name):
    return [l.strip() for l in open(LISTS / name, encoding="utf-8") if l.strip() and not l.startswith("#")]


def literal(w):
    if not w or any(c in "'\\" or (ord(c) < 32) for c in w):
        raise ValueError(f"word not allowed in a grammar: {w!r}")
    return "'" + w + "'"


def lexer(name, words, header):
    words = sorted(set(words), key=lambda w: (-len(w), w))
    body = "\n    | ".join(literal(w) for w in words)
    return f"// generated by gen_words.py from src/lists/ ({header}); do not edit\nlexer grammar {name};\nWORD : {body} ;\nANY  : . ;\n"


def main():
    groups = {}
    for l in read("suspicious_words.tsv")[1:]:
        w, g = l.split("\t")
        groups.setdefault(g, []).append(w)
    stop = set(read("brand_stoplist.txt"))
    brands = {l.split("\t")[0] for l in read("brands.txt") if int(l.split("\t")[1]) <= 500} - stop
    grammars = {"WordsPhrase": lexer("WordsPhrase", groups["phrase"], "suspicious_words.tsv, group phrase"),
                "WordsBrand": lexer("WordsBrand", groups["brand"], "suspicious_words.tsv, group brand"),
                "WordsHost": lexer("WordsHost", groups["host"], "suspicious_words.tsv, group host"),
                "WordsBrandLong": lexer("WordsBrandLong", [b for b in brands if len(b) >= 6], "brands.txt minus brand_stoplist.txt, length >= 6"),
                "WordsToken": "// generated by gen_words.py; do not edit\nlexer grammar WordsToken;\nWORD : [a-z0-9]+ ;\nANY  : . ;\n"}
    for name, text in grammars.items():
        (HERE / f"{name}.g4").write_text(text)
        subprocess.run(["java", "-jar", str(HERE / "antlr-4.13.2-complete.jar"), "-Dlanguage=Python3", "-Xexact-output-dir", "-o", str(OUT), str(HERE / f"{name}.g4")], check=True, cwd=HERE)
        print(name, "ok")


if __name__ == "__main__":
    main()
